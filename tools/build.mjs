/* ---- register + html ---- */
const register = JSON.parse(fs.readFileSync(src('register.json'), 'utf8'));
const problems = validateRegister(register);
if (problems.length) { console.error('register invalid:\n' + problems.join('\n')); process.exit(1); }
fs.copyFileSync(src('register.json'), out('register.json'));
const R = register.records;

let html = fs.readFileSync(src('index.html'), 'utf8');
const rpcHost = isStated(R.rpc) ? hostOf(R.rpc.url) : null;
const marketBoot = isStated(R.market) ? JSON.stringify({ state: 'stated', url: R.market.url, pairsUrl: R.market.pairsUrl }) : 'null';
const slots = {
  NIGHT: night.hex,
  CHAIN_CHIP: renderChip(R.chain),
  SOCIAL: renderSocial('x', R.x) + renderSocial('github', R.github),
  CA: renderCA(R.ca),
  TIERS: ['tier1', 'tier2', 'tier3'].map((id) => renderTile(id, R[id])).join(''),
  VAULT: ['vault', 'refunded', 'opened', 'cap', 'fee'].map((id) => renderTile(id, R[id])).join(''),
  FOOT: renderChip(R.chain) + (rpcHost ? `<span class="chip"><span class="label">${R.rpc.label}</span><span class="chip-v">${rpcHost}</span></span>` : '') + (isStated(R.domain) ? `<span class="chip"><span class="label">${R.domain.label}</span><span class="chip-v">${R.domain.value}</span></span>` : ''),
};
for (const [k, v] of Object.entries(slots)) html = html.replaceAll(`{{${k}}}`, v);
html = html.replace('<html lang="en">', `<html lang="en" data-market='${marketBoot}'>`);
fs.writeFileSync(out('index.html'), html);

