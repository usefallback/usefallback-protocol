/* ---- logo: premultiplied area resize ---- */
function readPng(p) { return PNG.sync.read(fs.readFileSync(p)); }
function resizePremult(png, dw, dh, crop) {
  const { width: sw, data } = png;
  const c = crop || { x: 0, y: 0, w: png.width, h: png.height };
  const dst = new PNG({ width: dw, height: dh });
  const fx = c.w / dw, fy = c.h / dh;
  for (let y = 0; y < dh; y++) for (let x = 0; x < dw; x++) {
    const x0 = c.x + x * fx, x1 = x0 + fx, y0 = c.y + y * fy, y1 = y0 + fy;
    let r = 0, g = 0, b = 0, a = 0, wsum = 0;
    for (let sy = Math.floor(y0); sy < Math.ceil(y1); sy++) {
      const wy = Math.min(sy + 1, y1) - Math.max(sy, y0);
      for (let sx = Math.floor(x0); sx < Math.ceil(x1); sx++) {
        const wgt = wy * (Math.min(sx + 1, x1) - Math.max(sx, x0));
        const o = (sy * sw + sx) * 4, al = data[o + 3] / 255;
        r += data[o] * al * wgt; g += data[o + 1] * al * wgt; b += data[o + 2] * al * wgt; a += al * wgt; wsum += wgt;
      }
    }
    const o = (y * dw + x) * 4, A = a / wsum;
    dst.data[o] = A > 0 ? Math.round(r / wsum / A) : 0; // un-premultiply
    dst.data[o + 1] = A > 0 ? Math.round(g / wsum / A) : 0;
    dst.data[o + 2] = A > 0 ? Math.round(b / wsum / A) : 0;
    dst.data[o + 3] = Math.round(A * 255);
  }
  return PNG.sync.write(dst);
}

const tile = readPng(path.join(root, 'brand', 'LOGO FALLBACK PNG.png'));
const markSrc = readPng(path.join(root, 'brand', 'LOGO FALLBACK PNG...png'));
fs.writeFileSync(out('assets', 'logo-192.png'), resizePremult(tile, 192, 192));
fs.writeFileSync(out('assets', 'logo-512.png'), resizePremult(tile, 512, 512));

// mark: alpha logo cropped to its ink box (alpha > 8), 4% pad, resized premultiplied
let bx0 = markSrc.width, by0 = markSrc.height, bx1 = 0, by1 = 0;
for (let y = 0; y < markSrc.height; y++) for (let x = 0; x < markSrc.width; x++) {
  if (markSrc.data[(y * markSrc.width + x) * 4 + 3] > 8) { if (x < bx0) bx0 = x; if (x > bx1) bx1 = x; if (y < by0) by0 = y; if (y > by1) by1 = y; }
}
const cw = bx1 - bx0 + 1, ch2 = by1 - by0 + 1;
fs.writeFileSync(out('assets', 'logo-mark.png'), resizePremult(markSrc, 960, Math.round(960 * ch2 / cw), { x: bx0, y: by0, w: cw, h: ch2 }));

/* ---- favicon: 32 columns across the ink box of the logo's real pixel grid ---- */
{
  const { width: w, data } = tile;
  const dark = (x, y) => { const o = (y * w + x) * 4; return data[o] + data[o + 1] + data[o + 2] < 200; };
  let x0 = w, y0 = w, x1 = 0, y1 = 0;
  for (let y = 0; y < tile.height; y++) for (let x = 0; x < w; x++) if (dark(x, y)) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
  const cell = (x1 - x0 + 1) / 32, rows = Math.ceil((y1 - y0 + 1) / cell), offY = Math.floor((32 - rows) / 2);
  const grid = [];
  for (let j = 0; j < rows; j++) {
    let line = '';
    for (let i = 0; i < 32; i++) {
      let n = 0, t = 0;
      for (let sy = Math.floor(y0 + j * cell); sy < Math.floor(y0 + (j + 1) * cell); sy += 2) for (let sx = Math.floor(x0 + i * cell); sx < Math.floor(x0 + (i + 1) * cell); sx += 2) { t++; if (dark(sx, sy)) n++; }
      line += t && n / t >= 0.5 ? '1' : '0';
    }
    grid.push(line);
  }
  let d = '';
  grid.forEach((line, j) => { for (const m of line.matchAll(/1+/g)) d += `M${m.index} ${j + offY}h${m[0].length}v1h-${m[0].length}z`; });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32" shape-rendering="crispEdges"><rect width="32" height="32" fill="${volt.hex}"/><path fill="${night.hex}" d="${d}"/></svg>\n`;
  fs.writeFileSync(out('favicon.svg'), svg);
  fs.writeFileSync(path.join(root, 'tools', 'favicon-grid.txt'), grid.join('\n') + '\n');
}

